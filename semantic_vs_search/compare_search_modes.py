# ---------------------------------------------------------------- input ----

def tok(text: str) -> list[str]:
    return _WORD.findall(text.lower()) if text else []


def latest_file(folder: str, pattern: str = "*") -> str | None:
    candidates = [p for p in glob(os.path.join(folder, pattern)) if os.path.isfile(p)]
    if not candidates:
        return None
    candidates.sort(key=lambda p: (os.path.getmtime(p), p))
    return candidates[-1]


def load_records(path: str) -> list[dict[str, Any]]:
    t0 = time.time()
    with open(path, "r", encoding="utf-8") as fh:
        first = fh.read(1)
        while first and first.isspace():
            first = fh.read(1)
    if first in ("[", "{"):
        try:
            with open(path, "r", encoding="utf-8") as fh:
                root = json.load(fh)
        except json.JSONDecodeError:
            root = None
        if root is not None:
            if isinstance(root, dict):
                for key in ("docs", "items", "records", "data", "results", "hits"):
                    value = root.get(key)
                    if isinstance(value, list) and value and all(isinstance(x, dict) for x in value):
                        root = value
                        break
            if not isinstance(root, list):
                raise ValueError("Could not find a list of records in the input JSON")
            log.info("Loaded %d records in %.1fs", len(root), time.time() - t0)
            return [r for r in root if isinstance(r, dict)]
    records = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    log.info("Loaded %d records (JSONL) in %.1fs", len(records), time.time() - t0)
    return records


def flatten_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, (int, float, bool)):
        return str(value)
    if isinstance(value, dict):
        for key in ("name", "title", "label", "value"):
            if value.get(key):
                return str(value[key]).strip()
        return " ".join(flatten_text(v) for v in value.values()).strip()
    if isinstance(value, (list, tuple, set)):
        return " ".join(flatten_text(v) for v in value).strip()
    return str(value).strip()


def detect_language(text: str) -> str:
    if not text or len(text) < 40:
        return "unknown"
    try:
        from langdetect import DetectorFactory, detect

        DetectorFactory.seed = 0
        return detect(text[:1200])
    except Exception:
        return "unknown"


# ------------------------------------------------- field-list resolution ----

def read_field_audit(reports_dir: str) -> tuple[list[str], str | None]:
    """Take the indexed-field list from the newest field audit report.

    Keeps this experiment and which_fields_to_choose in step instead of
    restating the field policy in two places.
    """
    path = latest_file(reports_dir, "field_audit_*.txt")
    if not path:
        return [], None
    try:
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("Full-text fields"):
                    _, _, rhs = line.partition(":")
                    fields = [f.strip() for f in rhs.split(",") if f.strip() and f.strip() != "-"]
                    if fields:
                        return fields, os.path.basename(path)
    except OSError:
        pass
    return [], None


def derive_held_out_fields(
    records: list[dict[str, Any]],
    index_fields: list[str],
    min_avg_words: float,
    max_fields: int,
) -> list[str]:
    """Text-bearing fields that are NOT indexed, ranked by how much text they carry.

    Derived rather than listed, so the experiment still has a query source if
    the field policy changes.
    """
    indexed = set(index_fields)
    stats: dict[str, list[int]] = defaultdict(list)
    sample = records[: min(len(records), 400)]
    for record in sample:
        for key, value in record.items():
            if key in indexed or key.startswith(("_", "@")):
                continue
            lowered = key.lower()
            if any(bit in lowered for bit in ("hash", "_fp", "fingerprint", "url", "doi", "id")):
                continue
            text = flatten_text(value)
            if text:
                stats[key].append(len(text.split()))
    scored = [
        (key, sum(lengths) / len(lengths))
        for key, lengths in stats.items()
        if len(lengths) >= max(3, 0.2 * len(sample))
    ]
    scored = [(k, avg) for k, avg in scored if avg >= min_avg_words]
    scored.sort(key=lambda kv: -kv[1])
    return [k for k, _ in scored[:max_fields]]


# ------------------------------------------- corpus-derived stopwords ------

def derive_stopwords(
    doc_tokens: list[list[str]],
    doc_langs: list[str],
    df_ratio: float,
    min_docs: int,
) -> tuple[dict[str, set[str]], set[str]]:
    """Terms that are too common to carry meaning, computed per language.

    A hand-written stopword list can only cover the languages whoever wrote it
    happened to know. On a 24-language corpus that quietly cleans queries in
    some languages and not others, which biases exactly the comparison this
    script exists to make. Document frequency treats every language alike.
    """
    by_lang: dict[str, list[list[str]]] = defaultdict(list)
    for tokens, lang in zip(doc_tokens, doc_langs):
        by_lang[lang].append(tokens)

    per_lang: dict[str, set[str]] = {}
    for lang, docs in by_lang.items():
        if lang == "unknown" or len(docs) < min_docs:
            continue
        df = Counter()
        for tokens in docs:
            df.update(set(tokens))
        n = len(docs)
        per_lang[lang] = {term for term, count in df.items() if count / n > df_ratio}

    df_all = Counter()
    for tokens in doc_tokens:
        df_all.update(set(tokens))
    n_all = max(1, len(doc_tokens))
    global_stop = {term for term, count in df_all.items() if count / n_all > df_ratio}
    return per_lang, global_stop


# ----------------------------------------------------------------- bm25 ----

class Bm25Index:
    """Same BM25 formulation as which_fields_to_choose/analyse_fields.py.

    A deliberate self-contained copy: this workspace keeps service folders
    independent rather than importing across them.
    """

    def __init__(self, docs_tokens: list[list[str]], k1: float = 1.2, b: float = 0.75) -> None:
        self.n_docs = len(docs_tokens)
        self.k1, self.b = k1, b
        df = Counter()
        dl = np.array([len(t) for t in docs_tokens], dtype=float)
        for tokens in docs_tokens:
            if tokens:
                df.update(set(tokens))
        self.idf = {
            term: math.log((self.n_docs - df[term] + 0.5) / (df[term] + 0.5) + 1.0)
            for term in df
        }
        avgdl = float(dl.mean()) if self.n_docs else 0.0
        self.den_vec = k1 * (1 - b + b * (dl / (avgdl or 1.0))) + 1e-12

        postings_docs: dict[str, list[int]] = defaultdict(list)
        postings_tfs: dict[str, list[int]] = defaultdict(list)
        for doc_id, tokens in enumerate(docs_tokens):
            if not tokens:
                continue
            for term, freq in Counter(tokens).items():
                postings_docs[term].append(doc_id)
                postings_tfs[term].append(freq)
        self.postings = {
            term: (
                np.fromiter(ids, dtype=np.int32, count=len(ids)),
                np.fromiter(postings_tfs[term], dtype=np.float64, count=len(ids)),
            )
            for term, ids in postings_docs.items()
        }
        self.empty = not self.postings

    def rank(self, query_tokens: list[str], k: int) -> list[int]:
        if not query_tokens or self.empty:
            return []
        scores = np.zeros(self.n_docs, dtype=np.float64)
        for term in set(query_tokens):
            weight = self.idf.get(term)
            hit = self.postings.get(term)
            if weight is None or hit is None:
                continue
            ids, tfs = hit
            scores[ids] += weight * ((tfs * (self.k1 + 1.0)) / (tfs + self.den_vec[ids]))
        nz = np.flatnonzero(scores > 0.0)
        if nz.size == 0:
            return []
        order = np.argsort(-scores[nz], kind="stable")[:k]
        return nz[order].tolist()


# ---------------------------------------------------------------- dense ----

def embed(texts: list[str], model_name: str, cache_dir: str, tag: str, batch_size: int = 32) -> np.ndarray:
    from sentence_transformers import SentenceTransformer

    fingerprint = hashlib.sha1(
        (model_name + "\x00" + "\x00".join(texts)).encode("utf-8", "ignore")
    ).hexdigest()[:16]
    os.makedirs(cache_dir, exist_ok=True)
    cache_path = os.path.join(cache_dir, f"{tag}_{fingerprint}.npy")
    if os.path.exists(cache_path):
        log.info("  [%s] reusing cached embeddings", tag)
        return np.load(cache_path)

    t0 = time.time()
    model = SentenceTransformer(model_name, device="cpu")
    vectors = model.encode(
        texts, batch_size=batch_size, convert_to_numpy=True,
        normalize_embeddings=True, show_progress_bar=False,
    ).astype(np.float32)
    log.info("  [%s] encoded %d texts in %.0fs", tag, len(texts), time.time() - t0)
    np.save(cache_path, vectors)
    return vectors


def dense_rank(query_vecs: np.ndarray, doc_vecs: np.ndarray, k: int) -> list[list[int]]:
    rankings = []
    k = min(k, doc_vecs.shape[0])
    for start in range(0, len(query_vecs), 256):
        sims = query_vecs[start:start + 256] @ doc_vecs.T
        top = np.argpartition(-sims, k - 1, axis=1)[:, :k]
        for row, cand in zip(sims, top):
            rankings.append(cand[np.argsort(-row[cand], kind="stable")].tolist())
    return rankings


def rrf_fuse(rankings: list[list[int]], k: int, rrf_k: int) -> list[int]:
    scores: dict[int, float] = defaultdict(float)
    for ranking in rankings:
        for rank, doc_id in enumerate(ranking, start=1):
            scores[doc_id] += 1.0 / (rrf_k + rank)
    return [d for d, _ in sorted(scores.items(), key=lambda kv: (-kv[1], kv[0]))[:k]]


# -------------------------------------------------------------- queries ----

def build_corpus(records: list[dict[str, Any]], index_fields: list[str], held_out_fields: list[str]):
    indexed, held_out = [], []
    for record in records:
        indexed.append(" ".join(t for t in (flatten_text(record.get(f)) for f in index_fields) if t))
        held_out.append(" ".join(t for t in (flatten_text(record.get(f)) for f in held_out_fields) if t))
    return indexed, held_out


def statistical_queries(
    target_ids: list[int],
    indexed: list[str],
    held_tokens: list[list[str]],
    idf: dict[str, float],
    stop_per_lang: dict[str, set[str]],
    global_stop: set[str],
    doc_langs: list[str],
    terms_per_query: int,
) -> list[dict[str, Any]]:
    """The two query types that need no model: most-distinctive terms, and the
    subset of those that the indexed text does not contain."""
    queries: list[dict[str, Any]] = []
    for idx in target_ids:
        stop = stop_per_lang.get(doc_langs[idx], global_stop)
        counts = Counter(
            t for t in held_tokens[idx]
            if len(t) > 2 and t not in stop and not t.isdigit()
        )
        if not counts:
            continue
        ranked = sorted(counts.items(), key=lambda kv: (-(kv[1] * idf.get(kv[0], 0.0)), kv[0]))
        topical = [t for t, _ in ranked[:terms_per_query]]
        if topical:
            queries.append({"target": idx, "type": "topical", "text": " ".join(topical)})
        indexed_tokens = set(tok(indexed[idx]))
        unseen = [t for t, _ in ranked if t not in indexed_tokens][:terms_per_query]
        if len(unseen) >= 4:
            queries.append({"target": idx, "type": "unseen-vocab", "text": " ".join(unseen)})
    return queries


QUERY_PROMPT = """You are helping evaluate a search engine for an EU agricultural
knowledge platform. Below is an excerpt from one document.

Return ONLY a JSON object, no commentary:
{{
  "lang": "<ISO 639-1 code of the excerpt's language>",
  "question": "<one natural question a farmer or advisor would type into a search box to find this document, written IN THE EXCERPT'S OWN LANGUAGE, 6-15 words>",
  "question_other_lang": "<the same question translated into {other_language}>",
  "other_lang": "{other_code}",
  "paraphrase": "<describe what this document is about in 8-15 words, in English, WITHOUT reusing its distinctive technical terms - use everyday synonyms instead>"
}}

EXCERPT:
{excerpt}"""

# Chosen to span scripts and families actually present in EU-FarmBook content.
CROSS_LANGUAGE_CHOICES = [
    ("English", "en"), ("French", "fr"), ("Spanish", "es"), ("German", "de"),
    ("Italian", "it"), ("Polish", "pl"), ("Dutch", "nl"), ("Greek", "el"),
]


def llm_queries(
    client,
    target_ids: list[int],
    held_out: list[str],
    doc_langs: list[str],
    excerpt_chars: int,
    workers: int,
    seed: int,
) -> list[dict[str, Any]]:
    """Natural, paraphrase and cross-lingual queries, one LLM call per document."""
    rng = random.Random(seed)
    jobs = []
    for idx in target_ids:
        doc_lang = doc_langs[idx]
        choices = [c for c in CROSS_LANGUAGE_CHOICES if c[1] != doc_lang] or CROSS_LANGUAGE_CHOICES
        other_name, other_code = rng.choice(choices)
        jobs.append((idx, other_name, other_code))

    def worker(job):
        idx, other_name, other_code = job
        prompt = QUERY_PROMPT.format(
            other_language=other_name,
            other_code=other_code,
            excerpt=held_out[idx][:excerpt_chars],
        )
        return idx, client.complete_json(prompt, max_tokens=320)

    results = client.map_concurrent(jobs, worker, workers=workers, label="queries")

    queries: list[dict[str, Any]] = []
    for item in results:
        if not item:
            continue
        idx, data = item
        if not isinstance(data, dict):
            continue
        question = (data.get("question") or "").strip()
        other = (data.get("question_other_lang") or "").strip()
        paraphrase = (data.get("paraphrase") or "").strip()
        detected = (data.get("lang") or "").strip().lower()[:2] or doc_langs[idx]
        other_code = (data.get("other_lang") or "").strip().lower()[:2]
        if len(question.split()) >= 3:
            queries.append({"target": idx, "type": "natural", "text": question, "query_lang": detected})
        if len(paraphrase.split()) >= 4:
            queries.append({"target": idx, "type": "paraphrase", "text": paraphrase, "query_lang": "en"})
        if len(other.split()) >= 3 and other_code and other_code != detected:
            queries.append({
                "target": idx, "type": "cross-lingual", "text": other,
                "query_lang": other_code, "doc_lang": detected,
            })
    return queries


# -------------------------------------------------------------- judging ----

JUDGE_PROMPT = """You are judging search results for an EU agricultural knowledge platform.

QUERY: {query}

Below are candidate documents. For each, decide how well it answers the query.

Grades:
3 = directly answers the query; this is what the user wanted
2 = substantially about the query's topic and clearly useful
1 = related but only marginally useful
0 = not relevant

Return ONLY a JSON object mapping each candidate number to its grade, e.g.
{{"1": 3, "2": 0, "3": 1}}

CANDIDATES:
{candidates}"""


def judge_pool(
    client,
    queries: list[dict[str, Any]],
    pools: list[list[int]],
    doc_snippets: list[str],
    workers: int,
    batch_size: int,
) -> list[dict[int, int]]:
    """Grade every (query, pooled document) pair with the LLM.

    Standard pooling: the union of what all systems returned is judged, so no
    system is scored against a relevance set built from its own output. This
    replaces "only the source document counts", which penalises any retriever
    that surfaces other genuinely relevant documents.
    """
    jobs = []
    for qi, (query, pool) in enumerate(zip(queries, pools)):
        for start in range(0, len(pool), batch_size):
            jobs.append((qi, pool[start:start + batch_size]))

    def worker(job):
        qi, doc_ids = job
        candidates = "\n\n".join(
            f"[{n}] {doc_snippets[d]}" for n, d in enumerate(doc_ids, start=1)
        )
        data = client.complete_json(
            JUDGE_PROMPT.format(query=queries[qi]["text"], candidates=candidates),
            max_tokens=260,
        )
        grades: dict[int, int] = {}
        if isinstance(data, dict):
            for key, value in data.items():
                try:
                    n = int(re.sub(r"\D", "", str(key)))
                    grade = int(value)
                except (TypeError, ValueError):
                    continue
                if 1 <= n <= len(doc_ids):
                    grades[doc_ids[n - 1]] = max(0, min(3, grade))
        return qi, grades

    results = client.map_concurrent(jobs, worker, workers=workers, label="judging")

    qrels: list[dict[int, int]] = [dict() for _ in queries]
    for item in results:
        if not item:
            continue
        qi, grades = item
        qrels[qi].update(grades)
    return qrels


# -------------------------------------------------------------- metrics ----

def per_query_rr(rankings: list[list[int]], targets: list[int], k: int) -> np.ndarray:
    out = np.zeros(len(rankings))
    for i, (ranking, target) in enumerate(zip(rankings, targets)):
        for rank, doc_id in enumerate(ranking[:k], start=1):
            if doc_id == target:
                out[i] = 1.0 / rank
                break
    return out


def per_query_hit(rankings: list[list[int]], targets: list[int], k: int) -> np.ndarray:
    return np.array([1.0 if t in r[:k] else 0.0 for r, t in zip(rankings, targets)])


def per_query_ndcg(rankings: list[list[int]], qrels: list[dict[int, int]], k: int) -> np.ndarray:
    out = np.zeros(len(rankings))
    for i, (ranking, rels) in enumerate(zip(rankings, qrels)):
        if not rels:
            continue
        dcg = sum(
            (2 ** rels.get(doc_id, 0) - 1) / math.log2(rank + 1)
            for rank, doc_id in enumerate(ranking[:k], start=1)
        )
        ideal = sorted(rels.values(), reverse=True)[:k]
        idcg = sum((2 ** g - 1) / math.log2(r + 1) for r, g in enumerate(ideal, start=1))
        out[i] = dcg / idcg if idcg > 0 else 0.0
    return out


def summarise(scores: np.ndarray, seed: int) -> dict[str, float]:
    mean, lo, hi = mean_ci(scores, seed=seed)
    return {"mean": mean, "lo": lo, "hi": hi, "n": int(scores.size)}


