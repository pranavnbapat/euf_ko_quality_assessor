"""
Keyword (BM25) vs semantic (dense) retrieval on the real KO corpus.

Design rules this script follows:

1. Nothing that varies with the data is hardcoded. Stopwords are derived from
   the corpus per language, the indexed and held-out field lists are read from
   the latest field audit, and every remaining constant is a CLI flag.
2. Queries are generated by an LLM in the document's own language, so no step
   depends on Latin capitalisation or on "." ending a sentence. Both fail on
   part of a 24-language corpus.
3. Relevance is judged by an LLM over a pool built from all systems, not by
   assuming the one source document is the only correct answer. Single-target
   scoring silently penalises semantic retrieval, which is the thing under test.
4. Every claim in the verdict is backed by a paired bootstrap test, so the
   report distinguishes a real difference from noise.

Retrievers only ever see the fields the field audit recommends indexing.
Queries are built only from text that is not indexed, so no mode can win by
matching a string it was also handed.
"""

